// Builds and previews the static, read-only version for GitHub Pages (see README, section "GitHub Pages").
//   node scripts/pages.mjs build     (npm run build:pages)    builds web/dist with the data from site-data/
//   node scripts/pages.mjs preview   (npm run preview:pages)  starts vite preview on the result
// Platform independent (Windows, Linux), hence a Node script instead of environment variables in package.json.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

// import.meta.dirname is the folder of this file (ESM replacement for __dirname); the repo root is one level up.
const root = path.resolve(import.meta.dirname, '..');
// Input: JSON files generated by "npm run export:static". Output: Vite build folder web/dist.
const siteData = path.join(root, 'site-data');
const dist = path.join(root, 'web', 'dist');

// VITE_DATA_MODE=static makes the web app read the JSON files instead of calling the API.
// Base path of the site: https://<account>.github.io/<repo>/ -> "/<repo>/". Can be changed via VITE_BASE (e.g. "/" for
// a custom domain).
const env = { ...process.env, VITE_DATA_MODE: 'static', VITE_BASE: process.env.VITE_BASE ?? '/gw2-fractal-items/' };

/** Runs a shell command in the repo root and exits this script with the same code if it fails. */
function run(command) {
    // A single command string with shell: npm is a .cmd file on Windows.
    const result = spawnSync(command, { cwd: root, env, stdio: 'inherit', shell: true });
    if (result.status !== 0) process.exit(result.status ?? 1);
}

/** Prints an error and exits with code 1. */
function fail(message) {
    console.error(message);
    process.exit(1);
}

// First command line argument: "build" or "preview".
const mode = process.argv[2];

if (mode === 'build') {
    if (!fs.existsSync(path.join(siteData, 'meta.json'))) {
        fail('site-data/ is missing or empty. Run "npm run export:static" first and commit the result.');
    }
    run('npm run build --workspace web');
    fs.cpSync(siteData, path.join(dist, 'data'), { recursive: true });
    // GitHub Pages serves 404.html for unknown paths. As a copy of index.html it starts the app there
    // and reads the path from the URL: reload and deep links like /gw2-fractal-items/items/123 work.
    fs.copyFileSync(path.join(dist, 'index.html'), path.join(dist, '404.html'));
    console.log(`Pages build done: ${dist} (base ${env.VITE_BASE}). Preview: npm run preview:pages`);
} else if (mode === 'preview') {
    if (!fs.existsSync(path.join(dist, 'data', 'meta.json')))
        fail('No Pages build found. Run "npm run build:pages" first.');
    run('npm run preview --workspace web');
} else {
    fail('Usage: node scripts/pages.mjs build|preview');
}
